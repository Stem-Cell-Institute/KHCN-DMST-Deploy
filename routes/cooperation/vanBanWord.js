'use strict';

/**
 * Hợp tác quốc tế — Văn bản Word & mẫu Tờ trình cho 4 loại (doan-ra, doan-vao, mou, ytnn).
 * Mỗi loại gồm 7 route (28 route tổng cộng, giữ nguyên thứ tự đăng ký cũ).
 *
 * Tách khỏi server.js (Đợt 5.9 của readme/KE-HOACH-REFACTOR.md), giữ NGUYÊN hành vi.
 * Lưới an toàn: tests/cooperationHtqtEvents.test.js.
 */

const express = require('express');
const fs = require('fs');
const path = require('path');

module.exports = function createCoopVanBanWordRouter({
  db,
  uploadDir,
  authMiddleware,
  adminOnly,
  storedUploadsPathForDatabase,
  resolveStoredFileFromDb,
  pathIsStrictlyInsideResolvedRoot,
  // doan-ra
  uploadHtqtDoanRa,
  uploadToTrinhTemplate,
  DOAN_RA_TO_TRINH_TEMPLATE_PATH,
  coopUnlinkDoanRaVanBanFile,
  coopCanDownloadDoanRaVanBan,
  coopEnsureFreshDoanRaVanBan,
  coopTryAutoGenerateDoanRaVanBan,
  // doan-vao
  uploadHtqtDoanVao,
  uploadToTrinhTemplateDoanVao,
  DOAN_VAO_TO_TRINH_TEMPLATE_PATH,
  coopUnlinkDoanVaoVanBanFile,
  coopCanDownloadDoanVaoVanBan,
  coopEnsureFreshDoanVaoVanBan,
  coopTryAutoGenerateDoanVaoVanBan,
  // mou
  uploadHtqtMou,
  uploadToTrinhTemplateMou,
  MOU_TO_TRINH_TEMPLATE_PATH,
  coopUnlinkMouVanBanFile,
  coopCanDownloadMouVanBan,
  coopEnsureFreshMouVanBan,
  coopTryAutoGenerateMouVanBan,
  // ytnn
  uploadHtqtYtnn,
  uploadToTrinhTemplateYtnn,
  YTNN_TO_TRINH_TEMPLATE_PATH,
  coopUnlinkYtnnVanBanFile,
  coopCanDownloadYtnnVanBan,
  coopEnsureFreshYtnnVanBan,
  coopTryAutoGenerateYtnnVanBan,
}) {
  const router = express.Router();

  const configs = [
    {
      slug: 'doan-ra',
      logTag: 'doan_ra',
      table: 'cooperation_doan_ra',
      subDir: 'htqt-doan-ra',
      defaultFile: 'van-ban-doan-ra.docx',
      tplDownloadName: 'mau-to-trinh-doan-ra.docx',
      tplPrompt: 'Chọn file .docx (mẫu Tờ trình Đoàn ra, có placeholder {ma_so}, {quoc_gia}, …).',
      tplSavedMsg: 'Đã lưu mẫu Tờ trình Đoàn ra (.docx).',
      noTplMsg: 'Chưa có file mẫu .docx. Admin vui lòng tải lên mẫu Tờ trình (menu trong chi tiết Đoàn ra).',
      uploadDoc: uploadHtqtDoanRa,
      uploadTpl: uploadToTrinhTemplate,
      tplPath: DOAN_RA_TO_TRINH_TEMPLATE_PATH,
      unlinkFile: coopUnlinkDoanRaVanBanFile,
      canDownload: coopCanDownloadDoanRaVanBan,
      ensureFresh: coopEnsureFreshDoanRaVanBan,
      tryAutoGen: coopTryAutoGenerateDoanRaVanBan,
    },
    {
      slug: 'doan-vao',
      logTag: 'doan_vao',
      table: 'cooperation_doan_vao',
      subDir: 'htqt-doan-vao',
      defaultFile: 'van-ban-doan-vao.docx',
      tplDownloadName: 'mau-to-trinh-doan-vao.docx',
      tplPrompt: 'Chọn file .docx (mẫu Tờ trình Đoàn vào, có placeholder {ma_so}, {don_vi_de_xuat}, …).',
      tplSavedMsg: 'Đã lưu mẫu Tờ trình Đoàn vào (.docx).',
      noTplMsg: 'Chưa có file mẫu .docx. Admin vui lòng tải lên mẫu Tờ trình (menu trong chi tiết Đoàn vào).',
      uploadDoc: uploadHtqtDoanVao,
      uploadTpl: uploadToTrinhTemplateDoanVao,
      tplPath: DOAN_VAO_TO_TRINH_TEMPLATE_PATH,
      unlinkFile: coopUnlinkDoanVaoVanBanFile,
      canDownload: coopCanDownloadDoanVaoVanBan,
      ensureFresh: coopEnsureFreshDoanVaoVanBan,
      tryAutoGen: coopTryAutoGenerateDoanVaoVanBan,
    },
    {
      slug: 'mou',
      logTag: 'mou',
      table: 'cooperation_mou_de_xuat',
      subDir: 'htqt-mou',
      defaultFile: 'van-ban-mou.docx',
      tplDownloadName: 'mau-to-trinh-mou.docx',
      tplPrompt: 'Chọn file .docx (mẫu Tờ trình Thỏa thuận/MOU, có placeholder {ma_so}, {ten_doi_tac}, …).',
      tplSavedMsg: 'Đã lưu mẫu Tờ trình Đề xuất Thỏa thuận (.docx).',
      noTplMsg: 'Chưa có file mẫu .docx. Admin vui lòng tải lên mẫu Tờ trình (menu trong chi tiết Đề xuất Thỏa thuận).',
      uploadDoc: uploadHtqtMou,
      uploadTpl: uploadToTrinhTemplateMou,
      tplPath: MOU_TO_TRINH_TEMPLATE_PATH,
      unlinkFile: coopUnlinkMouVanBanFile,
      canDownload: coopCanDownloadMouVanBan,
      ensureFresh: coopEnsureFreshMouVanBan,
      tryAutoGen: coopTryAutoGenerateMouVanBan,
    },
    {
      slug: 'ytnn',
      logTag: 'ytnn',
      table: 'htqt_de_xuat',
      subDir: 'htqt-ytnn',
      defaultFile: 'van-ban-ytnn.docx',
      tplDownloadName: 'mau-to-trinh-ytnn.docx',
      tplPrompt: 'Chọn file .docx (mẫu Tờ trình YTNN: {ma_so}, {ten_de_tai}, {mo_ta_de_tai}, {ten_to_chuc_doi_tac}, {quoc_gia_doi_tac}, {chu_nhiem_de_tai}, {hoc_ham_hoc_vi}, {don_vi_chu_nhiem}, {kinh_phi}, {don_vi_tien_te}, {tieu_de_to_trinh}, {nguoi_phe_duyet}, …).',
      tplSavedMsg: 'Đã lưu mẫu Tờ trình Đề tài YTNN (.docx).',
      noTplMsg: 'Chưa có file mẫu .docx. Admin vui lòng tải lên mẫu Tờ trình (menu trong chi tiết Đề tài YTNN).',
      uploadDoc: uploadHtqtYtnn,
      uploadTpl: uploadToTrinhTemplateYtnn,
      tplPath: YTNN_TO_TRINH_TEMPLATE_PATH,
      unlinkFile: coopUnlinkYtnnVanBanFile,
      canDownload: coopCanDownloadYtnnVanBan,
      ensureFresh: coopEnsureFreshYtnnVanBan,
      tryAutoGen: coopTryAutoGenerateYtnnVanBan,
    },
  ];

  for (const cfg of configs) {
    const {
      slug, logTag, table, subDir, defaultFile, tplDownloadName, tplPrompt, tplSavedMsg, noTplMsg,
      uploadDoc, uploadTpl, tplPath, unlinkFile, canDownload, ensureFresh, tryAutoGen,
    } = cfg;

    router.post(`/admin/cooperation/${slug}/:id/van-ban-word`, authMiddleware, adminOnly, (req, res) => {
      const id = parseInt(req.params.id, 10);
      if (!id) return res.status(400).json({ message: 'ID không hợp lệ.' });
      const row = db.prepare(`SELECT * FROM ${table} WHERE id=?`).get(id);
      if (!row) return res.status(404).json({ message: 'Không tìm thấy đề xuất.' });
      if ((row.status || '').toLowerCase() !== 'da_duyet') {
        return res.status(400).json({ message: 'Chỉ upload văn bản Word sau khi đề xuất đã được phê duyệt.' });
      }
      uploadDoc.single('file')(req, res, (err) => {
        if (err) return res.status(400).json({ message: 'Lỗi upload' });
        if (!req.file) return res.status(400).json({ message: 'Chọn file .doc hoặc .docx.' });
        const rel = storedUploadsPathForDatabase(req.file.path);
        unlinkFile(row);
        const orig = (req.file.originalname || 'van-ban.docx').replace(/[<>:"/\\|?*\x00-\x1f]/g, '_');
        db.prepare(`UPDATE ${table} SET van_ban_word_path=?, van_ban_word_original_name=?, van_ban_word_uploaded_at=datetime('now','localtime'), updated_at=datetime('now','localtime') WHERE id=?`)
          .run(rel, orig, id);
        return res.json({ ok: true, message: 'Đã lưu văn bản Word.', van_ban_word_original_name: orig });
      });
    });

    router.delete(`/admin/cooperation/${slug}/:id/van-ban-word`, authMiddleware, adminOnly, (req, res) => {
      const id = parseInt(req.params.id, 10);
      if (!id) return res.status(400).json({ message: 'ID không hợp lệ.' });
      const row = db.prepare(`SELECT * FROM ${table} WHERE id=?`).get(id);
      if (!row) return res.status(404).json({ message: 'Không tìm thấy.' });
      unlinkFile(row);
      db.prepare(`UPDATE ${table} SET van_ban_word_path=NULL, van_ban_word_original_name=NULL, van_ban_word_uploaded_at=NULL, updated_at=datetime('now','localtime') WHERE id=?`).run(id);
      return res.json({ ok: true, message: 'Đã xóa file văn bản.' });
    });

    router.get(`/cooperation/${slug}/:id/van-ban-word`, authMiddleware, (req, res) => {
      const id = parseInt(req.params.id, 10);
      if (!id) return res.status(400).json({ message: 'ID không hợp lệ.' });
      let row = db.prepare(`SELECT * FROM ${table} WHERE id=?`).get(id);
      if (!row) return res.status(404).json({ message: 'Không tìm thấy đề xuất.' });
      if ((row.status || '').toLowerCase() !== 'da_duyet') {
        return res.status(400).json({ message: 'Chỉ tải được khi đề xuất đã được phê duyệt.' });
      }
      if (!canDownload(req, row)) {
        return res.status(403).json({ message: 'Bạn không có quyền tải file này.' });
      }
      row = ensureFresh(id);
      if (!row || !row.van_ban_word_path) return res.status(404).json({ message: 'Chưa có văn bản Word.' });
      const abs = resolveStoredFileFromDb(row.van_ban_word_path);
      const baseDir = path.resolve(path.join(uploadDir, subDir));
      if (!abs || !pathIsStrictlyInsideResolvedRoot(baseDir, abs)) {
        return res.status(400).json({ message: 'Đường dẫn file không hợp lệ.' });
      }
      if (!fs.existsSync(abs)) return res.status(404).json({ message: 'File không còn trên máy chủ.' });
      res.setHeader('Access-Control-Expose-Headers', 'Content-Disposition');
      res.download(abs, row.van_ban_word_original_name || defaultFile);
    });

    router.post(`/admin/cooperation/${slug}/to-trinh-template`, authMiddleware, adminOnly, (req, res) => {
      uploadTpl.single('file')(req, res, (err) => {
        if (err) return res.status(400).json({ message: 'Lỗi upload' });
        if (!req.file) return res.status(400).json({ message: tplPrompt });
        return res.json({ ok: true, message: tplSavedMsg });
      });
    });

    router.get(`/admin/cooperation/${slug}/to-trinh-template`, authMiddleware, adminOnly, (req, res) => {
      if (!fs.existsSync(tplPath)) return res.status(404).json({ message: 'Chưa có file mẫu.' });
      res.download(tplPath, tplDownloadName);
    });

    router.get(`/cooperation/${slug}/to-trinh-template/status`, authMiddleware, (req, res) => {
      const exists = fs.existsSync(tplPath);
      let updatedAt = null;
      if (exists) {
        try { updatedAt = fs.statSync(tplPath).mtime.toISOString(); } catch (e) {}
      }
      return res.json({ hasTemplate: exists, updatedAt });
    });

    router.post(`/admin/cooperation/${slug}/:id/sinh-to-trinh-word`, authMiddleware, adminOnly, (req, res) => {
      const id = parseInt(req.params.id, 10);
      if (!id) return res.status(400).json({ message: 'ID không hợp lệ.' });
      const row = db.prepare(`SELECT * FROM ${table} WHERE id=?`).get(id);
      if (!row) return res.status(404).json({ message: 'Không tìm thấy đề xuất.' });
      if ((row.status || '').toLowerCase() !== 'da_duyet') {
        return res.status(400).json({ message: 'Chỉ sinh tờ trình khi đề xuất đã được phê duyệt.' });
      }
      const gen = tryAutoGen(id);
      if (gen.skipped === 'no_template') {
        return res.status(400).json({ message: noTplMsg });
      }
      if (gen.skipped === 'not_approved') {
        return res.status(400).json({ message: 'Chỉ sinh tờ trình khi đề xuất đã được phê duyệt.' });
      }
      if (!gen.ok) {
        console.error(`[merge] ${logTag}`, gen.message);
        return res.status(400).json({ message: gen.message || 'Lỗi khi ghép Word.' });
      }
      return res.json({ ok: true, message: 'Đã sinh file Word từ mẫu và dữ liệu đề xuất.', van_ban_word_original_name: gen.outName });
    });
  }

  return router;
};
